class PurchaseRfqQuote(Base):
    __tablename__ = "purchase_rfq_quotes"

    id: Mapped[str] = mapped_column(String(36), primary_key=True, default=lambda: str(uuid.uuid4()))
    purchase_rfq_id: Mapped[str] = mapped_column(
        String(36),
        ForeignKey("purchase_rfqs.id", ondelete="CASCADE"),
        nullable=False,
        index=True,
    )
    supplier_id: Mapped[str] = mapped_column(
        String(36),
        ForeignKey("commerce_suppliers.id", ondelete="RESTRICT"),
        nullable=False,
        index=True,
    )
    # Free text — the SUPPLIER's own reference string. Never generated by us.
    quote_number: Mapped[Optional[str]] = mapped_column(String(64), nullable=True)
    status: Mapped[str] = mapped_column(String(20), nullable=False, default="submitted", index=True)
    valid_until: Mapped[Optional[date]] = mapped_column(Date, nullable=True)
    lead_time_days: Mapped[int] = mapped_column(Integer, nullable=False, default=0)
    moq: Mapped[int] = mapped_column(Integer, nullable=False, default=0)
    # Always computed server-side from line_quotes — never trust a client total.
    total_amount: Mapped[Decimal] = mapped_column(Numeric(14, 2), nullable=False, default=0)
    submitted_at: Mapped[Optional[datetime]] = mapped_column(DateTime, nullable=True)
    # "manual" (recorded by staff) or "portal" (supplier self-serve) — mirrors
    # SupplierProduct.api_source's provenance-tracking pattern.
    source: Mapped[str] = mapped_column(String(20), nullable=False, default="manual")
    notes: Mapped[Optional[str]] = mapped_column(Text, nullable=True)
    created_at: Mapped[datetime] = mapped_column(DateTime, nullable=False, server_default=func.now())
    updated_at: Mapped[datetime] = mapped_column(
        DateTime,
        nullable=False,
        server_default=func.now(),
        onupdate=func.now(),
    )


