"""Build the AI data dictionary from the live database (docs/AI/ai.md, step 0.2).

For every table that belongs to an ERP module (the same table -> module map the AI's query tool uses) it records the columns,
their types, the foreign keys (so the AI can join to a NAME table), the approximate row count and - for status / type / stage
style columns - the values actually in use. Auth / secret tables and secret-looking columns are never written.

Output: app/services/ai/knowledge/data_dictionary.generated.json  (rebuild any time the schema changes; commit the result).
Hand-written meaning goes in knowledge/definitions.json (business definitions) - never edit the generated file by hand.

Usage (api container):
    python -m scripts.build_ai_data_dictionary
"""
from __future__ import annotations

import json
import re
from datetime import datetime, timezone
from pathlib import Path

from sqlalchemy import text

import scripts.init_db  # noqa: F401 - registers every model
from app.database import SessionLocal
from app.services.ai.tools.database_tools import BLOCKED_COLUMN_RE, MODULE_LABELS, _blocked_table, table_modules

OUT = Path(__file__).resolve().parents[1] / "app" / "services" / "ai" / "knowledge" / "data_dictionary.generated.json"
# a column whose values are a short list worth knowing (status, type, stage ...)
ENUM_NAME = re.compile(r"(^|_)(status|type|stage|state|kind|method|reason|channel|source|priority|direction|mode|tier|group|category)$", re.I)
TEXT_TYPES = {"character varying", "text", "character"}
MAX_VALUES = 12


def main() -> None:
    db = SessionLocal()
    cols = db.execute(text(
        "SELECT table_name, column_name, data_type, is_nullable FROM information_schema.columns "
        "WHERE table_schema = 'public' ORDER BY table_name, ordinal_position"
    )).all()
    fks = db.execute(text(
        "SELECT tc.table_name, kcu.column_name, ccu.table_name, ccu.column_name "
        "FROM information_schema.table_constraints tc "
        "JOIN information_schema.key_column_usage kcu ON tc.constraint_name = kcu.constraint_name AND tc.table_schema = kcu.table_schema "
        "JOIN information_schema.constraint_column_usage ccu ON ccu.constraint_name = tc.constraint_name AND ccu.table_schema = tc.table_schema "
        "WHERE tc.constraint_type = 'FOREIGN KEY' AND tc.table_schema = 'public'"
    )).all()
    rows = dict(db.execute(text(
        "SELECT c.relname, GREATEST(c.reltuples, 0)::bigint FROM pg_class c JOIN pg_namespace n ON n.oid = c.relnamespace "
        "WHERE n.nspname = 'public' AND c.relkind = 'r'"
    )).all())
    fk_of = {(t, c): f"{rt}.{rc}" for t, c, rt, rc in fks}

    tables: dict[str, dict] = {}
    for t, c, dtype, nullable in cols:
        if _blocked_table(t) or not table_modules(t) or BLOCKED_COLUMN_RE.search(c):
            continue
        entry = tables.setdefault(t, {"module": table_modules(t)[0], "approx_rows": int(rows.get(t, 0)), "columns": []})
        col = {"name": c, "type": dtype, "nullable": nullable == "YES"}
        if (t, c) in fk_of:
            col["fk"] = fk_of[(t, c)]
        tables[t]["columns"].append(col)

    probed = 0
    for t, entry in tables.items():
        for col in entry["columns"]:
            if col["type"] not in TEXT_TYPES or not ENUM_NAME.search(col["name"]):
                continue
            try:
                db.execute(text("SET LOCAL statement_timeout = 4000"))
                vals = db.execute(text(f'SELECT "{col["name"]}", count(*) FROM "{t}" GROUP BY 1 ORDER BY 2 DESC LIMIT {MAX_VALUES + 1}')).all()
            except Exception:  # noqa: BLE001 - a column we cannot read is simply not described
                db.rollback()
                continue
            db.rollback()
            values = [str(v) for v, _ in vals if v is not None]
            if 0 < len(values) <= MAX_VALUES:
                col["values"] = values
                probed += 1

    by_module: dict[str, dict] = {}
    for t, entry in sorted(tables.items()):
        m = entry.pop("module")
        by_module.setdefault(m, {"label": MODULE_LABELS.get(m, m), "tables": {}})["tables"][t] = entry
    doc = {
        "generated_at": datetime.now(timezone.utc).isoformat(timespec="seconds"),
        "note": "Generated by scripts/build_ai_data_dictionary.py - do not edit; business meaning lives in definitions.json",
        "tables": len(tables),
        "enum_columns": probed,
        "modules": by_module,
    }
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(json.dumps(doc, ensure_ascii=False, indent=1), encoding="utf-8")
    print(f"{len(tables)} tables in {len(by_module)} modules, {probed} enum-like columns -> {OUT}")
    for m, d in by_module.items():
        print(f"  {m:13} {len(d['tables'])} tables")
    db.close()


if __name__ == "__main__":
    main()
