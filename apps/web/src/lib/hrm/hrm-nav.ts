/** Flat list of stub screens (excludes full CRUD screens like employees/dashboard). */
export function listHrmStubScreens(): { href: string; title: string; description: string }[] {
  const skip = new Set(["/hrm/dashboard", "/hrm/employees", "/hrm/calendar"]);
  const out: { href: string; title: string; description: string }[] = [];
  for (const menu of HRM_NAV_MENUS) {
    for (const entry of menu.children) {
      if (entry.kind !== "item") continue;
      if (skip.has(entry.href)) continue;
      out.push({
        href: entry.href,
        title: entry.label,
        description: entry.description ?? `${entry.label} screen.`,
      });
    }
  }
  return out;
}
